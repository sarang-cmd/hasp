// Generates src/web/icons.js from the vendored Heroicons solid set.
//
// Heroicons (https://heroicons.com/solid) is MIT licensed by Tailwind Labs. The
// glyphs are vendored under src/web/heroicons/ and their licence ships beside
// them, so the app still loads with no network and no runtime dependency.
//
// Run with `npm run icons` after changing the set.

import { readFileSync, writeFileSync, mkdirSync, copyFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const SRC = join(ROOT, "node_modules/heroicons/24/solid");
const OUT_DIR = join(ROOT, "src/web/heroicons");
const OUT = join(ROOT, "src/web/icons.js");

/**
 * The names the app uses, mapped to Heroicons glyphs. Keeping our own names means
 * a glyph can be swapped without touching every call site, and the mapping is
 * readable when reviewing a diff.
 */
const SET = {
  vault: "circle-stack",
  search: "magnifying-glass",
  copy: "document-duplicate",
  plus: "plus",
  lock: "lock-closed",
  unlock: "lock-open",
  eye: "eye",
  eyeoff: "eye-slash",
  clock: "clock",
  key: "key",
  gear: "cog-6-tooth",
  close: "x-mark",
  download: "arrow-down-tray",
  upload: "arrow-up-tray",
  check: "check",
  alert: "exclamation-triangle",
  trash: "trash",
  edit: "pencil-square",
  sun: "sun",
  moon: "moon",
  layers: "square-3-stack-3d",
  activity: "bolt",
  device: "computer-desktop",
  refresh: "arrow-path",
  arrow: "arrow-right",
};

/** Strip the outer <svg>, keep the body, and normalise the viewBox to 24. */
function body(name) {
  const raw = readFileSync(join(SRC, `${name}.svg`), "utf8");
  const inner = raw.slice(raw.indexOf(">") + 1, raw.lastIndexOf("</svg>")).trim();
  return inner.replace(/\s+/g, " ").replace(/>\s+</g, "><");
}

const entries = Object.entries(SET).map(([ours, hero]) => [ours, hero, body(hero)]);

const file = `// Generated by tools/icons.mjs. Do not edit by hand.
//
// Icons are Heroicons solid, 24px grid, drawn with fill and no stroke.
// Heroicons is MIT licensed; the licence is vendored at heroicons/LICENSE.
//
// Every glyph is inlined here rather than fetched, so the app renders its chrome
// before any network request and works offline. Solid glyphs carry no stroke
// attributes at all: a single shape, one colour, legible down to 14px.

const wrap = (inner, size = 16) =>
  \`<svg viewBox="0 0 24 24" width="\${size}" height="\${size}" fill="currentColor" aria-hidden="true" focusable="false">\${inner}</svg>\`;

const paths = {
${entries.map(([ours, hero, inner]) => `  // Heroicons: ${hero}\n  ${ours}: ${JSON.stringify(inner)},`).join("\n")}
};

/** An icon by our name, rendered at a size in px. */
export const icon = (name, size = 16) => (paths[name] ? wrap(paths[name], size) : "");

/** The icon set, already wrapped, for templates that interpolate directly. */
export const icons = Object.fromEntries(Object.keys(paths).map((k) => [k, wrap(paths[k])]));

export const ICON_NAMES = Object.keys(paths);

/** The product mark: a shackle rising out of a bolted hasp plate. */
export const mark = (size = 22) =>
  \`<svg viewBox="0 0 128 128" width="\${size}" height="\${size}" aria-hidden="true" focusable="false"><path d="M44 78V56a20 20 0 0 1 40 0v22" fill="none" stroke="currentColor" stroke-width="14" stroke-linecap="round"/><rect x="18" y="72" width="92" height="34" rx="10" fill="currentColor"/><circle cx="40" cy="89" r="6" fill="var(--bg)"/><circle cx="88" cy="89" r="6" fill="var(--bg)"/></svg>\`;

/** A brand mark, served from src/web/brands by slug. */
export const brandMark = (slug, alt = "") =>
  slug
    ? \`<img src="brands/\${encodeURIComponent(slug)}.svg" alt="\${escAttr(alt)}" width="18" height="18" loading="lazy" decoding="async">\`
    : "";

function escAttr(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}
`;

mkdirSync(OUT_DIR, { recursive: true });
// Vendor the glyphs too, so the generated file can be regenerated offline and a
// reader can see exactly what was taken.
for (const [, hero] of Object.entries(SET)) {
  copyFileSync(join(SRC, `${hero}.svg`), join(OUT_DIR, `${hero}.svg`));
}
copyFileSync(join(ROOT, "node_modules/heroicons/LICENSE"), join(OUT_DIR, "LICENSE"));

writeFileSync(OUT, file);
console.log(`icons.js: ${entries.length} glyphs from heroicons/24/solid`);
console.log(`vendored into src/web/heroicons (${readdirSync(OUT_DIR).length} files, licence included)`);
