/**
 * The pairing this device holds for pushing its own records out.
 *
 * Server side, "pairing" means "this vault may write to a sync store". The token is
 * a write credential for that store, not a key: it cannot read a secret, because a
 * secret is ciphertext the store has no key for.
 */
let syncPairing = null;

/**
 * What happened, newest last.
 *
 * An entry names an action, an item and a time. It never carries a value, a note or a
 * code, so reading this file tells you what was touched and not what it contained.
 * Capped, because a log that grows without a limit is a disk leak dressed as a feature.
 */
let activity = [];

/** Kinds the log understands. A typo here shows up as an unknown action, not silence. */
const ACTIONS = new Set(["created", "edited", "copied", "deleted", "restored", "synced"]);

/**
 * Record one event.
 * @param {string} action one of ACTIONS
 * @param {{id?: string, name?: string}} item
 */
function recordActivity(action, item = {}) {
  if (!ACTIONS.has(action)) throw new Error(`unknown action: ${action}`);
  activity.push({
    action,
    id: item.id || null,
    // Truncated, because a name is a label and not a place to hide a secret. The vault
    // already limits a name to 120 characters.
    name: String(item.name || "").slice(0, 120),
    at: new Date().toISOString(),
  });
  if (activity.length > ACTIVITY_MAX) activity = activity.slice(-ACTIVITY_MAX);
}

/** Write the log beside the vault. Separate file, so a corrupted log cannot lose a vault. */
async function persistActivity() {
  if (EPHEMERAL) return;
  await mkdir(VAULT_DIR, { recursive: true });
  await writeFile(ACTIVITY_FILE, JSON.stringify({ entries: activity }, null, 2), { mode: 0o600 });
}

/**
 * The conflict log.
 *
 * PLAN.md calls for last write wins with a visible log, and a conflict that exists
 * only in one response is not visible to anyone who was not watching. Each entry
 * names an item by id only: the store cannot read a name, and this file should not
 * invent one, so the client resolves the id against its own vault.
 *
 * Capped, because a log that grows without limit is a disk leak. Oldest entries go.
 */
let syncLog = [];
const SYNC_LOG_MAX = 200;

/** Record one conflict. Ids and revisions only, never content. */
function logConflict({ id, local, remote, at = new Date().toISOString() }) {
  syncLog.push({ id, local, remote, at });
  if (syncLog.length > SYNC_LOG_MAX) syncLog = syncLog.slice(-SYNC_LOG_MAX);
}

/** A pending pairing and the paired devices. Memory only: a restart revokes all. */
let pairing = null;
let devices = [];
const pairingSeen = new Map();
const PAIRING_TTL = 120;
let bootPassword = null;

/**
 * The parsed import awaiting a decision. Bound to a single use: accepting clears
 * it, so a second accept cannot store the same candidates again, and it expires
 * so a forgotten tab cannot store an old parse hours later.
 */
const IMPORT_TTL_MS = 30 * 60 * 1000;
let pendingImport = null;

function setPendingImport(candidates) {
  pendingImport = { candidates, at: Date.now() };
}

function takePendingImport() {
  const p = pendingImport;
  pendingImport = null;
  if (!p) return null;
  if (Date.now() - p.at > IMPORT_TTL_MS) return null;
  return p.candidates;
}

/* ---------------------------------------------------------------- storage */

async function persist() {
  if (EPHEMERAL || !vault) return;
  await mkdir(VAULT_DIR, { recursive: true });
  const data = JSON.stringify(vault.serialize(), null, 2);
  await writeFile(VAULT_FILE, data, { mode: 0o600 });
  // Written together, so an entry cannot describe a write that did not land, or be
  // missing for one that did.
  await persistActivity();
}

async function bootVault() {
  if (existsSync(VAULT_FILE) && !EPHEMERAL) {
    const stored = JSON.parse(await readFile(VAULT_FILE, "utf8"));
    // The preview has no way to ask for the password before a request, so a
    // persisted vault is reopened with the sample password. A real deployment
    // unlocks per session instead.
    vault = await Vault.unlock(stored, SAMPLE_PASSWORD);
    // A sync pairing is recorded beside the vault so a restart does not silently
    // stop the other device from syncing. A missing or unreadable record just means
    // this machine is not paired, which is a safe default.
    try {
      const pairing = JSON.parse(await readFile(join(VAULT_DIR, "sync-pairing.json"), "utf8"));
      if (pairing?.vaultId === vault.meta.id && pairing?.token) syncPairing = pairing;
      if (Array.isArray(pairing?.log)) syncLog = pairing.log.slice(-SYNC_LOG_MAX);
    } catch {
      // Not paired yet.
    }
    // Outside the pairing block on purpose: a machine that has never synced still has
    // a log, and nesting this inside the pairing read would have made the log appear
    // empty on exactly those machines.
    try {
      const log = JSON.parse(await readFile(ACTIVITY_FILE, "utf8"));
      if (Array.isArray(log?.entries)) activity = log.entries.slice(-ACTIVITY_MAX);
    } catch {
      // No log yet, or one that cannot be read. Both mean an empty log, and neither
      // is a reason to refuse to open a vault.
    }
    console.log("vault: reopened from .vault/vault.json");
    return;
  }
  vault = await Vault.create({ name: "Sarang, personal", password: SAMPLE_PASSWORD });
  await seedVault(vault);
  bootPassword = SAMPLE_PASSWORD;
  await persist();
  console.log(`vault: seeded with sample items (password: ${SAMPLE_PASSWORD})`);
}

